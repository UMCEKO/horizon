//! Borrowed call constructors and checked writeback plumbing.
//!
//! Owned API values explicitly derive `Wire` or implement their checked encoding beside
//! the type. The generator emits only the adapters whose signatures come from call tables.
use super::ty::{BorrowedShape, Types};
use std::fmt::Write;

/// Borrowed record constructors, projections and writeback.
pub(super) fn calls(types: &Types<'_>) -> String {
    let mut out = String::from("// @generated by horizon-mod-api-gen; do not edit.\n");
    for (def_id, def) in types.defs.iter().enumerate() {
        // Host-side imports must also reconstruct non-exhaustive borrowed records.
        // A typed constructor generated from public fields keeps this structural, not per-type glue.
        if def.lifetimes == 1
            && let BorrowedShape::Record(fields) = &def.borrowed
            && fields
                .iter()
                .all(|f| super::calls::held(types, &f.ty).is_some())
        {
            let args = fields
                .iter()
                .map(|f| {
                    format!(
                        "{}: {}",
                        f.rust,
                        borrowed(types, &f.ty)
                            .replace("'_", "'a")
                            .replace("&", "&'a ")
                            .replace("&'a 'static", "&'static")
                    )
                })
                .collect::<Vec<_>>()
                .join(",");
            let names = fields
                .iter()
                .map(|f| f.rust.as_str())
                .collect::<Vec<_>>()
                .join(",");
            writeln!(out, "#[doc(hidden)] pub fn __wire_record_{def_id}<'a>({args}) -> {}<'a> {{ {} {{ {names} }} }}", def.rust, def.rust).unwrap();
        }
        if def.append.is_some() || def.projection.is_some() {
            let put = def
                .borrow_fields()
                .unwrap()
                .iter()
                .map(|f| super::host::put(&f.ty, &format!("self.{}", f.rust)))
                .collect::<Vec<_>>()
                .join("");
            let path = &def.rust;
            writeln!(out, "impl crate::wire::Put for {path}<'_> {{ fn put_to(&self,w:&mut crate::wire::Writer) {{ {put} }} }}").unwrap();
        }
        if let Some(append) = &def.append {
            let element = super::calls::rust_ty(types, &append.element, false);
            let field = &append.fields[append.field].rust;
            let equal = &append.equal;
            let path = &def.rust;
            writeln!(out, "impl {path}<'_> {{
                    #[doc(hidden)] pub fn __wire_changes(&self) -> &Vec<{element}> {{ self.{field} }}
                    #[doc(hidden)] pub fn __wire_checked(&self, mut snapshot:Vec<{element}>) -> Result<crate::wire::Append<{element}>,crate::wire::WireError> {{
                        let prefix = snapshot.get(..self.{field}.len()).ok_or(crate::wire::WireError::Invalid(\"deleted append prefix\"))?;
                        if !self.{field}.iter().zip(prefix).all(|(a,b)| {equal}) {{ return Err(crate::wire::WireError::Invalid(\"changed append prefix\")); }}
                        drop(snapshot.drain(..self.{field}.len()));
                        Ok(crate::wire::Append::new(snapshot))
                    }}
                    #[doc(hidden)] pub fn __wire_apply(&mut self, delta:crate::wire::Append<{element}>) {{ self.{field}.extend(delta.into_vec()); }}
                }}").unwrap();
        }
        if let Some(view) = &def.view {
            let path = def.rust.split('<').next().unwrap();
            let snapshot = super::calls::rust_ty(types, &view.snapshot, false);
            let field = &view.field;
            writeln!(out,"impl crate::wire::Put for {path}<'_> {{ fn put_to(&self,out:&mut crate::wire::Writer) {{ out.put(&*self.{field}); }} }} impl {path}<'_> {{ #[doc(hidden)] pub fn __wire_put_snapshot(&self,out:&mut crate::wire::Writer) {{ out.put(&*self.{field}); }} #[doc(hidden)] pub fn __wire_apply(&mut self,snapshot:{snapshot}) {{ self.{field}.apply_snapshot(snapshot); }} }}").unwrap();
        }
    }
    out
}

/// A record field's type for its constructor, a nested borrowing record keeping the constructor's
/// lifetime (`Option<TerrainUvShift<'a>>`).
fn borrowed(types: &super::ty::Types<'_>, ty: &super::ty::Ty) -> String {
    use super::ty::Ty;
    match ty {
        Ty::Named(def) if types.defs[*def].lifetimes > 0 => {
            format!("{}<'_>", types.defs[*def].rust)
        }
        Ty::Option(item) => format!("Option<{}>", borrowed(types, item)),
        ty => super::calls::rust_ty(types, ty, false),
    }
}
