def cmd_trace_check(args):
    import subprocess
    text = subprocess.run(['jfr', 'print', '--events', 'jdk.MethodTrace', args.file], check=True, capture_output=True, text=True).stdout
    results = trace_check(trace_keys(read_verdicts(), owners_rows(args.owners)), trace_events(text))
    for key, ok in results:
        print(f'{"ok" if ok else "MISSING"}\t{key}')
    return 0 if all(ok for _, ok in results) else 1


