#!/usr/bin/env python3
"""W12's gates: which vanilla methods native routes to Java's merged method, checked against the routes reference packs need.

  gates [--check]     write mods/horizon/src/java-mods-host/boot/res/route_gates.tsv from the `route!` and `gui_route!` sites
  lint [--ledger] [--routing F]...
                      every reference-pack route, and every route of each install's routing.json, is gated or deferred
                      with a fixed reason; every gate is well placed
  report --routing F  a table of an install's routes and what covers each
"""
import argparse
import collections
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GATES_TSV = ROOT / 'mods/horizon/src/java-mods-host/boot/res/route_gates.tsv'
DATA = ROOT / 'tools/java_routing'
PACKS = DATA / 'packs'
DEFERRED = DATA / 'deferred.tsv'
TEST_ROUTES = DATA / 'test_routes.tsv'
LEDGER = ROOT / '.local/port-ledger/ledger.json'
HEADER = '# generated by tools/java_routing.py gates\n'

ROUTE = re.compile(r'(?<![\w!])route!\(\s*[\w.&*]+\s*,\s*"([^"]+)"')
GUI_ROUTE = re.compile(r'(?<![\w!])gui_route!\(\s*"([^"]+)"')
FN = re.compile(r'\bfn\s+(\w+)')
IMPL = re.compile(r'^[ \t]*(?:unsafe\s+)?impl\b[^\n{]*', re.M)
BODY_CALL = re.compile(r'\s*(?:return\s+)?self\.(\w+)\(')
REASON = re.compile(r'^(worldgen: W10|client: phase C|view: (entity|block_entity|scoreboard|save_stream|connection)|seam: lift|seam: \S+:\d+|special: (animate|item_code|sounds|screens)|verdict: undecided)')
PARTIAL = re.compile(r'^seam: \S+:\d+')


def skip_literal(text, i):
    """The index after the string, char or comment that starts at text[i], or i when none does."""
    if text.startswith('//', i):
        end = text.find('\n', i)
        return len(text) if end < 0 else end
    if text.startswith('/*', i):
        end = text.find('*/', i + 2)
        return len(text) if end < 0 else end + 2
    if text[i] == '"':
        j = i + 1
        while j < len(text) and text[j] != '"':
            j += 2 if text[j] == '\\' else 1
        return j + 1
    if text[i] == "'":
        m = re.match(r"'(?:\\[^']+|[^'\\])'", text[i:])
        if m:
            return i + m.end()
    return i


def match_close(text, i, open_char, close_char):
    """The index of the bracket closing the one at text[i], skipping literals and comments; -1 when unbalanced."""
    depth, j = 0, i
    while j < len(text):
        skipped = skip_literal(text, j)
        if skipped != j:
            j = skipped
            continue
        if text[j] == open_char:
            depth += 1
        elif text[j] == close_char:
            depth -= 1
            if depth == 0:
                return j
        j += 1
    return -1


def line_of(text, pos):
    return text.count('\n', 0, pos) + 1


def enclosing_fn(text, pos):
    """(name, index of its opening brace) of the nearest fn before pos, or None."""
    found = None
    for m in FN.finditer(text, 0, pos):
        found = m
    if found is None:
        return None
    brace = text.find('{', found.end())
    return (found.group(1), brace) if 0 <= brace < pos else None


def in_game_impl(text, pos):
    last = None
    for m in IMPL.finditer(text, 0, pos):
        last = m
    return last is not None and re.search(r'\bGame\b', last.group(0)) is not None


def fn_text(text, name):
    """The body of `fn name` (first definition), or None."""
    m = re.search(r'\bfn\s+' + re.escape(name) + r'\b', text)
    if not m:
        return None
    brace = text.find('{', m.end())
    if brace < 0:
        return None
    end = match_close(text, brace, '{', '}')
    return text[brace:end + 1] if end > 0 else None


def scan_text(text, path='<text>'):
    """The gates of one source text: dicts with key, kind (game/gui), file, line, fn, first, game, body."""
    gates = []
    for m in ROUTE.finditer(text):
        if text[:m.start()].rsplit('\n', 1)[-1].lstrip().startswith('//'):
            continue
        fn = enclosing_fn(text, m.start())
        paren = text.find('(', m.start())
        end = match_close(text, paren, '(', ')')
        after = BODY_CALL.match(text, text.find(';', end) + 1) if end > 0 else None
        gates.append({'key': m.group(1), 'kind': 'game', 'file': path, 'line': line_of(text, m.start()), 'fn': fn[0] if fn else '?',
                      'first': fn is not None and text[fn[1] + 1:m.start()].strip() == '', 'game': in_game_impl(text, m.start()),
                      'body': after.group(1) if after else None, 'text': text})
    for m in GUI_ROUTE.finditer(text):
        if text[:m.start()].rsplit('\n', 1)[-1].lstrip().startswith('//'):
            continue
        fn = enclosing_fn(text, m.start())
        gates.append({'key': m.group(1), 'kind': 'gui', 'file': path, 'line': line_of(text, m.start()), 'fn': fn[0] if fn else '?',
                      'first': True, 'game': True, 'body': None, 'text': text})
    return gates


def scan_tree(root=ROOT):
    gates = []
    for path in sorted((root / 'crates').rglob('*.rs')):
        text = path.read_text(errors='replace')
        if 'route!(' in text:
            gates += scan_text(text, path.relative_to(root).as_posix())
    return gates


def route_bridges(root=ROOT):
    """{(owner, name, desc)} of the `route` entries of the java_bridges tables; the entry pattern is java_mods.py's."""
    try:
        from . import java_mods as jm
    except ImportError:
        import java_mods as jm
    found = set()
    for path in sorted((root / 'crates/horizon-client/src/game/java').rglob('*.rs')):
        text = path.read_text()
        for m in jm.BRIDGE_ENTRY.finditer(text):
            if re.search(r'\broute\s*$', text[:m.start()]):
                found.add((m.group(1), m.group(2), m.group(3)))
    return found


def read_tsv(path):
    if not path.is_file():
        return []
    return [line.split('\t') for line in path.read_text().splitlines() if line.strip() and not line.startswith('#')]


def read_packs(directory=PACKS):
    """{key: {kind, family, tail, returns, mods}} over the reference packs' TSVs."""
    packs = {}
    for path in sorted(directory.glob('*.tsv')):
        for row in read_tsv(path):
            key, kind, family, tail, returns, mods = row[:6]
            packs.setdefault(key, {'kind': kind, 'family': family, 'tail': tail == '1', 'returns': int(returns), 'mods': set()})['mods'].update(mods.split(','))
    return packs


def routing_packs(routing):
    """{key: {kind, family, tail, returns, mods}} of an install's routing.json, as read_packs gives a reference pack's; a route inert by its guards needs no gate."""
    return {key: {'kind': r['kind'], 'family': r['family'], 'tail': bool(r['tail']), 'returns': int(r['returns']),
                  'mods': {c['mod'] for c in r['changes']}} for key, r in routing['routes'].items() if not r.get('inert')}


def merge_packs(packs, more):
    """`packs` with `more`'s routes added; a key both name keeps the first's shape and both mod sets."""
    merged = {key: {**pack, 'mods': set(pack['mods'])} for key, pack in packs.items()}
    for key, pack in more.items():
        merged.setdefault(key, {**pack, 'mods': set()})['mods'].update(pack['mods'])
    return merged


def read_deferred(path=DEFERRED):
    """[(key, reason)], one row per deferral; a key may have several partial-seam rows."""
    return [(row[0], row[1] if len(row) > 1 else '') for row in read_tsv(path)]


def read_test_routes(path=TEST_ROUTES):
    return {row[0] for row in read_tsv(path)}


def gui_rows(root=ROOT):
    keys = set()
    for path in sorted((root / 'mods/horizon/src/java-mods-host').rglob('gui_bridges.tsv')):
        keys |= {row[0] for row in read_tsv(path)}
    return keys


def partial_sites(deferred):
    return collections.Counter(key for key, reason in deferred if PARTIAL.match(reason))


def gates_tsv(gates, deferred):
    partial = partial_sites(deferred)
    rows = sorted({(g['key'], f'{g["file"]}:{g["line"]}', g['fn'], g['kind'], str(partial.get(g['key'], 0))) for g in gates})
    return HEADER + ''.join('\t'.join(row) + '\n' for row in rows)


def lint(gates, packs, deferred, test_routes, bridges, gui_keys, root_text=None):
    """Every failure, one per line. `bridges` is the set of route bridge entries (owner, name, desc)."""
    errors = []
    game = [g for g in gates if g['kind'] == 'game']
    gated = {g['key'] for g in gates}
    deferred_keys = collections.defaultdict(list)
    for key, reason in deferred:
        deferred_keys[key].append(reason)
        if not REASON.match(reason):
            errors.append(f'{key}: bad deferral reason {reason!r}')
    for key in sorted(packs):
        if key not in gated and key not in deferred_keys:
            errors.append(f'{key}: unrouted (no route! gate and no row in deferred.tsv)')
    for key in sorted(gated & set(deferred_keys)):
        if not all(PARTIAL.match(r) for r in deferred_keys[key]):
            errors.append(f'{key}: gated and deferred, remove the deferral')
    for g in game:
        key = g['key']
        where = f'{g["file"]}:{g["line"]}'
        if not (g['first'] and g['game']):
            errors.append(f'{key}: gate not first in a Game method ({where})')
        owner, _, rest = key.partition('#')
        pack = packs.get(key)
        if pack and pack['kind'] == 'edge' and (owner, rest.split('(')[0], rest[rest.index('('):]) not in bridges:
            errors.append(f'{key}: edge gate without a route bridge entry ({where})')
        if pack and pack['tail'] and pack['returns'] > 1:
            body = fn_text(g['text'], g['body']) if g['body'] else None
            if body is None or 'route::early(' not in body:
                errors.append(f'{key}: TAIL route with {pack["returns"]} returns but its body fn has no route::early ({where})')
    for key in sorted({g['key'] for g in game}):
        if key not in packs:
            if key in test_routes:
                continue
            errors.append(f'{key}: stale gate (no reference pack routes it)')
    rows = gui_keys
    gui = {g['key'] for g in gates if g['kind'] == 'gui'}
    for key in sorted(gui - rows):
        errors.append(f'{key}: gui_route! marker without a row in gui_bridges.tsv')
    for key in sorted(rows - gui):
        errors.append(f'{key}: gui_bridges.tsv row without a gui_route! marker')
    return errors


def ledger_lint(gates, packs, deferred, ledger, routing=None):
    """(errors, notes) from the port ledger: ports that bypass a gate, super-calling subclasses without a gate, undecided counts."""
    try:
        from . import mod_replaces as mr
    except ImportError:
        import mod_replaces as mr
    native = mr.Native(ledger)
    fns = ledger['fns']
    callers = collections.defaultdict(set)
    for i, f in enumerate(fns):
        for callee in f.get('callees', []):
            callers[callee].add(i)
    errors, notes = [], []
    by_key = collections.defaultdict(list)
    for g in gates:
        if g['kind'] == 'game':
            by_key[g['key']].append(g)

    def holds(i, gs):
        f = fns[i]
        return any((f['file'] == g['file'] and f['name'] == g['fn'] and f['line'] <= g['line'] <= f['end']) or f['name'] == g['body'] for g in gs)

    def below(roots):
        """The fns reachable from `roots` through callees."""
        seen, todo = set(roots), list(roots)
        while todo:
            for callee in fns[todo.pop()].get('callees', []):
                if callee not in seen:
                    seen.add(callee)
                    todo.append(callee)
        return seen

    def dispatches(i, gs):
        """Whether fn `i` calls a gated fn, so it reaches the port through the gate."""
        return any(holds(c, gs) for c in fns[i].get('callees', []))

    for key, gs in sorted(by_key.items()):
        short = key.split('(')[0]
        for kind in mr.STATUS_ORDER:
            ids = native.fn_ids(ledger.get(kind, {}).get(short, []))
            if ids:
                break
        else:
            ids = []
        inside = below([i for i in range(len(fns)) if holds(i, gs)])
        for i in ids:
            if holds(i, gs) or i in inside or dispatches(i, gs):
                continue
            outside = sorted(c for c in callers[i] if not (holds(c, gs) or c in inside or dispatches(c, gs) or fns[c]['file'] == fns[i]['file']))
            if outside:
                f = fns[i]
                errors.append(f'{key}: native port {f["file"]}:{f["name"]} bypasses the gate (called by {", ".join(fns[c]["file"] + ":" + fns[c]["name"] for c in outside[:3])})')
        for over in (routing or {}).get('routes', {}).get(key, {}).get('overriders', []):
            if not over.get('super_call'):
                continue
            sub = over['class'] + '#' + short.split('#')[1]
            for kind in mr.STATUS_ORDER:
                sub_ids = native.fn_ids(ledger.get(kind, {}).get(sub, []))
                if sub_ids:
                    break
            else:
                sub_ids = []
            if sub_ids and not any(holds(i, gs) for i in sub_ids):
                errors.append(f'{key}: {over["class"]} super-calls it but its port has no gate')
    undecided = sum(1 for _, reason in deferred if reason.startswith('verdict: undecided'))
    if undecided:
        notes.append(f'{undecided} deferrals are `verdict: undecided`')
    return errors, notes


def status_of(key, gated, deferred_by_key, inert=False):
    if inert:
        return 'inert (guard)'
    if key in gated:
        return 'gated'
    if key in deferred_by_key:
        return f'deferred ({deferred_by_key[key][0]})'
    return 'UNGATED'


def report_table(routing, gates=None, deferred=None):
    """Markdown lines: key | kind | family | mods | gated / deferred (reason) / UNGATED | needs_bridge."""
    gates = scan_tree() if gates is None else gates
    deferred = read_deferred() if deferred is None else deferred
    gated = {g['key'] for g in gates}
    by_key = collections.defaultdict(list)
    for key, reason in deferred:
        by_key[key].append(reason)
    rows = []
    for key, r in sorted(routing['routes'].items()):
        mods = ', '.join(sorted({c['mod'] for c in r['changes']}))
        need = ', '.join(n.split('#')[-1] for n in r['closure']['needs_bridge'])
        rows.append((key.replace('net/minecraft/', ''), r['kind'], r['family'], mods, status_of(key, gated, by_key, r.get('inert', False)), guards_text(r.get('guards')), need))
    lines = ['| key | kind | family | mods | status | guards | needs_bridge |', '|---|---|---|---|---|---|---|']
    lines += ['| ' + ' | '.join(f'`{c}`' if i == 0 else c for i, c in enumerate(row)) + ' |' for row in rows]
    counts = collections.Counter(row[4].split(' ')[0] for row in rows)
    covered = sum(n for k, n in counts.items() if k != 'UNGATED')
    return [f'{len(rows)} routes, {covered} covered: ' + ', '.join(f'{n} {k}' for k, n in sorted(counts.items())), ''] + lines


def guards_text(guards):
    """A route's guards for the report: `all`, or each narrowed field and its classes' simple names."""
    if not guards:
        return 'all'
    parts = []
    for field, value in guards.items():
        if isinstance(value, dict):
            parts += [f'{field}[{i}]: {", ".join(c.rsplit("/", 1)[-1] for c in classes)}' for i, classes in value.items()]
        elif value:
            parts.append(f'{field}: {", ".join(c.rsplit("/", 1)[-1] for c in value)}')
    return '; '.join(parts)


def gather(root=ROOT):
    gates = scan_tree(root)
    return gates, read_packs(), read_deferred(), read_test_routes(), route_bridges(root), gui_rows(root)


def cmd_gates(args):
    gates = scan_tree()
    text = gates_tsv(gates, read_deferred())
    if args.check:
        have = GATES_TSV.read_text() if GATES_TSV.is_file() else ''
        if have != text:
            print(f'{GATES_TSV.relative_to(ROOT)} is stale: run python3 tools/java_routing.py gates')
            return 1
        return 0
    GATES_TSV.parent.mkdir(parents=True, exist_ok=True)
    GATES_TSV.write_text(text)
    print(f'{len(text.splitlines()) - 1} gates in {GATES_TSV.relative_to(ROOT)}')
    return 0


def cmd_lint(args):
    gates, packs, deferred, test_routes, bridges, gui_keys = gather()
    routings = [json.loads(Path(path).read_text()) for path in args.routing or []]
    for routing in routings:
        packs = merge_packs(packs, routing_packs(routing))
    errors = lint(gates, packs, deferred, test_routes, bridges, gui_keys)
    if args.ledger:
        if not LEDGER.is_file():
            print(f'no port ledger at {LEDGER.relative_to(ROOT)}: skipping the ledger checks')
        else:
            routing = {'routes': {k: v for r in routings for k, v in r['routes'].items()}} if routings else None
            more, notes = ledger_lint(gates, packs, deferred, json.loads(LEDGER.read_text()), routing)
            errors += more
            for note in notes:
                print(note)
    for error in errors:
        print(error)
    return 1 if errors else 0


def cmd_report(args):
    print('\n'.join(report_table(json.loads(Path(args.routing).read_text()))))
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest='command', required=True)
    p = sub.add_parser('gates')
    p.add_argument('--check', action='store_true')
    p.set_defaults(run=cmd_gates)
    p = sub.add_parser('lint')
    p.add_argument('--ledger', action='store_true')
    p.add_argument('--routing', action='append', help='an install\'s routing.json (repeatable): its routes must be gated or deferred too')
    p.set_defaults(run=cmd_lint)
    p = sub.add_parser('report')
    p.add_argument('--routing', required=True)
    p.set_defaults(run=cmd_report)
    args = parser.parse_args(argv)
    sys.exit(args.run(args))


if __name__ == '__main__':
    main()
